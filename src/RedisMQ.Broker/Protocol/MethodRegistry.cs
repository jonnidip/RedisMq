namespace RedisMQ.Broker.Protocol;

/// <summary>
/// The direction a method canonically travels on the wire. This is a spec-level
/// annotation; the codegen fixture does not carry it, so the value lives with the
/// registry data. ClientToServer methods are requests the client sends; ServerToClient
/// methods are server-initiated flows and synchronous replies. Practical overlaps (the
/// server also sends connection.close / channel.close / channel.flow, and basic.cancel
/// when a queue is deleted) are state-machine behavior, not registry data.
/// </summary>
public enum Direction
{
    ClientToServer,
    ServerToClient,
}

/// <summary>
/// The wire form of a method argument: every base AMQP 0-9-1 type has one entry. The
/// bit family expresses the fixture's field-list order AND the AMQP bit-packing rule:
/// consecutive bit arguments form one packed octet group - a lone bit is
/// <see cref="Bit"/> (its own octet), the first bit of a run of 2+ is
/// <see cref="PackedBit"/> (it opens the group), the remaining run members are the
/// <see cref="DependingBit"/> chain. Each group occupies whole octets, LSB-first,
/// zero-padded to the octet boundary (RabbitMQ reference clients/errata behavior;
/// also pinned by the Task-1 ByteReader/ByteWriter tests).
/// </summary>
public enum WireType
{
    Octet,
    Short,
    Long,
    LongLong,
    Shortstr,
    Longstr,
    Table,
    Timestamp,
    Bit,
    PackedBit,
    DependingBit,
}

/// <summary>One argument of a method schema: the fixture's hyphenated wire name and its wire type.</summary>
public sealed record AmqpField(string Name, WireType Type);

/// <summary>
/// One basic-class content property. <see cref="FlagOrdinal"/> is the property's ordinal
/// in the fixture's property list; the content-header flag word maps ordinal n to bit
/// (15 - n) of the first 16-bit word (see ContentHeaderCodec's flag masks).
/// </summary>
public sealed record ContentProperty(string Name, WireType Type, int FlagOrdinal);

/// <summary>
/// The full descriptor of one 0-9-1 method: wire ids, the dotted fixture name
/// ("connection.start"), canonical direction, and the argument schema in fixture field
/// order with the bit-group classification.
/// </summary>
/// <param name="HasContent">True when the method is followed on the same channel by a
/// content header (and body frames) - the basic-class content-bearing methods.</param>
public sealed record MethodSchema(
    ushort ClassId,
    ushort MethodId,
    string Name,
    Direction Direction,
    IReadOnlyList<AmqpField> Fields)
{
    public bool HasContent { get; init; }
}

