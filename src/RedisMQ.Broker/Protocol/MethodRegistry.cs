    /// <summary>Every fixture method, in fixture file order (class order, then method order).</summary>
    public static IReadOnlyList<MethodSchema> All => _all;

    /// <summary>
    /// Looks up a method by its (classId, methodId) wire pair. Returns null when the pair
    /// is not in the dialect at all; callers (the server) decide what an unresolvable
    /// method becomes (e.g. not-implemented close).
    /// </summary>
    public static MethodSchema? Schema(int classId, ushort methodId) =>
        _byKey.TryGetValue((classId << 16) | methodId, out var schema) ? schema : null;

    /// <summary>Looks up a method by its dotted fixture name ("queue.declare").</summary>
    public static bool TryGetByName(string fullName, out MethodSchema? schema)
    {
        ArgumentNullException.ThrowIfNull(fullName);
        return _byName.TryGetValue(fullName, out schema);
    }

    /// <summary>
    /// The content properties of a class, in fixture order. Only the basic class carries
    /// content in 0-9-1; any other class resolves to null.
    /// </summary>
    public static IReadOnlyList<ContentProperty>? ContentProperties(int classId) =>
        classId == BasicClassId ? _basicContentProperties : null;

