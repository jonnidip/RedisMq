    private static readonly Dictionary<int, MethodSchema> _byKey;
    private static readonly Dictionary<string, MethodSchema> _byName;

    static MethodRegistry()
    {
        _byKey = new Dictionary<int, MethodSchema>(_all.Length);
        _byName = new Dictionary<string, MethodSchema>(_all.Length, StringComparer.Ordinal);
        foreach (var schema in _all)
        {
            if (!_byKey.TryAdd((schema.ClassId << 16) | schema.MethodId, schema))
            {
                throw new InvalidOperationException($"Duplicate method table entry: class {schema.ClassId} method {schema.MethodId} ({schema.Name})");
            }

            if (!_byName.TryAdd(schema.Name, schema))
            {
                throw new InvalidOperationException($"Duplicate method name: {schema.Name}");
            }
        }
    }

    /// <summary>Table row factory: keeps the generated table one field per line readable.</summary>
    private static MethodSchema M(ushort classId, ushort methodId, string name, Direction direction, bool content, params AmqpField[] fields) =>
        new MethodSchema(classId, methodId, name, direction, fields) { HasContent = content };

    private static AmqpField A(string name, WireType type) => new(name, type);
